#!/usr/bin/env bash
# Interactive notification setup for Claude Code xida plugin.
# Detects platform, presents sound/flash options, writes notification.conf.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONF="$SCRIPT_DIR/notification.conf"

# ── Detect platform ─────────────────────────────────

case "$OSTYPE" in
  msys*|cygwin*|MSYS*|CYGWIN*) PLATFORM="windows" ;;
  darwin*)                      PLATFORM="macos" ;;
  linux-gnu*)                   PLATFORM="linux" ;;
  *)
    echo "Unsupported platform: $OSTYPE"
    read -rp "Press Enter to exit..."
    exit 1
    ;;
esac

# ── Sound maps per platform ─────────────────────────

declare -a SOUND_NAMES
case "$PLATFORM" in
  windows)
    SOUND_NAMES=(
      "ding.wav"
      "chimes.wav"
      "Windows Exclamation.wav"
      "notify.wav"
      "chord.wav"
      "Windows Proximity Notification.wav"
      "tada.wav"
    )
    ;;
  macos)
    SOUND_NAMES=(
      "Tink"
      "Glass"
      "Ping"
      "Purr"
      "Hero"
      "Submarine"
      "Sosumi"
    )
    ;;
  linux)
    SOUND_NAMES=(
      "message-new-instant.oga"
      "complete.oga"
      "dialog-warning.oga"
      "bell.oga"
      "service-login.oga"
      "phone-incoming-call.oga"
      "dialog-information.oga"
    )
    ;;
esac

# ── Sound preview ────────────────────────────────────

play_preview() {
  local idx="$1"
  local name="${SOUND_NAMES[$((idx - 1))]}"
  case "$PLATFORM" in
    windows)
      powershell -NoProfile -Command "(New-Object Media.SoundPlayer 'C:\Windows\Media\\$name').PlaySync()" 2>/dev/null || true
      ;;
    macos)
      afplay "/System/Library/Sounds/${name}.aiff" 2>/dev/null || true
      ;;
    linux)
      local path="/usr/share/sounds/freedesktop/stereo/$name"
      if [ -f "$path" ]; then
        if command -v paplay &>/dev/null; then paplay "$path" 2>/dev/null || true
        elif command -v aplay &>/dev/null; then aplay "$path" 2>/dev/null || true
        fi
      else
        echo "  (sound file not found: $path)"
      fi
      ;;
  esac
}

# ── UI helpers ───────────────────────────────────────

show_header() {
  clear 2>/dev/null || true
  echo "========================================"
  echo "  Claude Code Notification Setup"
  echo "  Platform: $PLATFORM"
  echo "========================================"
  echo ""
}

show_sounds() {
  echo "Available sounds:"
  echo "  0) Off (no sound)"
  for i in "${!SOUND_NAMES[@]}"; do
    echo "  $((i + 1))) ${SOUND_NAMES[$i]}"
  done
  echo "  p) Preview all sounds"
  echo ""
}

ask_sound() {
  local event_label="$1"
  local default="$2"
  local choice
  while true; do
    read -rp "Sound for $event_label [0-7, p=preview] (default: $default): " choice
    choice="${choice:-$default}"
    if [ "$choice" = "p" ]; then
      echo "  Playing all sounds..." >&2
      for i in $(seq 1 ${#SOUND_NAMES[@]}); do
        echo "    $i) ${SOUND_NAMES[$((i - 1))]}" >&2
        play_preview "$i"
        sleep 0.3
      done
      echo "" >&2
      continue
    fi
    if [[ "$choice" =~ ^[0-7]$ ]]; then
      echo "$choice"
      return
    fi
    echo "  Invalid choice. Enter 0-7 or p." >&2
  done
}

ask_flash() {
  local event_label="$1"
  local default="$2"
  local choice
  read -rp "Taskbar flash for $event_label? [y/n] (default: $default): " choice
  choice="${choice:-$default}"
  case "$choice" in
    y|Y|yes|YES) echo "1" ;;
    *)           echo "0" ;;
  esac
}

# ── Load existing config ─────────────────────────────

STOP_SOUND=0
NOTIFICATION_SOUND=0
TASK_COMPLETE_SOUND=0
SUBAGENT_STOP_SOUND=0
STOP_FLASH=0
NOTIFICATION_FLASH=0
TASK_COMPLETE_FLASH=0
SUBAGENT_STOP_FLASH=0

if [ -f "$CONF" ]; then
  . "$CONF"
fi

# ── Main flow ────────────────────────────────────────

show_header
show_sounds

echo "Configure sound for each event (0=off, 1-7=sound):"
echo ""

STOP_SOUND=$(ask_sound "Stop (Claude finished)" "$STOP_SOUND")
NOTIFICATION_SOUND=$(ask_sound "Notification (needs attention)" "$NOTIFICATION_SOUND")
TASK_COMPLETE_SOUND=$(ask_sound "Task Complete" "$TASK_COMPLETE_SOUND")
SUBAGENT_STOP_SOUND=$(ask_sound "Subagent Stop" "$SUBAGENT_STOP_SOUND")

if [ "$PLATFORM" = "windows" ]; then
  echo ""
  echo "Configure taskbar flash for each event:"
  echo ""
  STOP_FLASH=$(ask_flash "Stop" "$([ "$STOP_FLASH" = "1" ] && echo y || echo n)")
  NOTIFICATION_FLASH=$(ask_flash "Notification" "$([ "$NOTIFICATION_FLASH" = "1" ] && echo y || echo n)")
  TASK_COMPLETE_FLASH=$(ask_flash "Task Complete" "$([ "$TASK_COMPLETE_FLASH" = "1" ] && echo y || echo n)")
  SUBAGENT_STOP_FLASH=$(ask_flash "Subagent Stop" "$([ "$SUBAGENT_STOP_FLASH" = "1" ] && echo y || echo n)")
fi

# ── Write config ─────────────────────────────────────

cat > "$CONF" << EOF
# Claude Code notification config -- generated by setup.sh
# Sound per event (0=off, 1-7=sound index)
STOP_SOUND=$STOP_SOUND
NOTIFICATION_SOUND=$NOTIFICATION_SOUND
TASK_COMPLETE_SOUND=$TASK_COMPLETE_SOUND
SUBAGENT_STOP_SOUND=$SUBAGENT_STOP_SOUND

# Taskbar flash per event (0=off, 1=on, Windows only)
STOP_FLASH=$STOP_FLASH
NOTIFICATION_FLASH=$NOTIFICATION_FLASH
TASK_COMPLETE_FLASH=$TASK_COMPLETE_FLASH
SUBAGENT_STOP_FLASH=$SUBAGENT_STOP_FLASH
EOF

echo ""
echo "========================================"
echo "  Configuration saved!"
echo "  File: $CONF"
echo "========================================"
echo ""
echo "Notifications are now active. Re-run /xida:notification to change settings."
echo ""
read -rp "Press Enter to close..."
