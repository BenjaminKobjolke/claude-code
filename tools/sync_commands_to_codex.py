"""Sync this repo's Claude `commands/` into Codex skills (~/.codex/skills/).

One-way: commands/ is the source of truth. Each commands/<cat>/<name>.md becomes
~/.codex/skills/<cat>-<name>/SKILL.md. Stale skills (from renamed/deleted commands)
are auto-removed via a marker file. Codex's own .system/ and symlinked skills are
never touched (no marker).

Run:  python sync_commands_to_codex.py        (or the .bat wrapper)
Test: python sync_commands_to_codex.py --self-test
"""

import shutil
import sys
from pathlib import Path

COMMANDS_DIR = Path(__file__).resolve().parent.parent / "commands"
SKILLS_DIR = Path.home() / ".codex" / "skills"
MARKER = ".synced-from-claude"

# Claude-only frontmatter keys that Codex skills don't use.
DROP_KEYS = {"effort", "allowed-tools", "argument-hint", "model", "name"}


def parse_frontmatter(text):
    """Return (description, body). description is None if absent.

    Only `description` is needed; we re-derive `name` from the path. The leading
    `---...---` block is stripped from body. Multi-line values aren't used by our
    commands, so a flat line parse is enough.
    """
    if not text.startswith("---"):
        return None, text
    lines = text.splitlines(keepends=True)
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end = i
            break
    if end is None:
        return None, text  # no closing fence; treat whole thing as body
    description = None
    for line in lines[1:end]:
        if ":" in line:
            key, _, val = line.partition(":")
            if key.strip() == "description":
                description = val.strip()
    body = "".join(lines[end + 1:]).lstrip("\n")
    return description, body


def build_skill_md(name, description, body):
    desc = description if description else name
    return f"---\nname: {name}\ndescription: {desc}\n---\n\n{body}"


def remove_stale(skills_dir):
    """Delete previously-synced skill folders (those carrying the marker)."""
    removed = 0
    if not skills_dir.exists():
        return removed
    for child in skills_dir.iterdir():
        if child.is_dir() and (child / MARKER).is_file():
            shutil.rmtree(child)
            removed += 1
    return removed


def sync():
    if not COMMANDS_DIR.is_dir():
        sys.exit(f"commands dir not found: {COMMANDS_DIR}")
    SKILLS_DIR.mkdir(parents=True, exist_ok=True)

    removed = remove_stale(SKILLS_DIR)

    # Resource files per category = non-.md siblings (e.g. setup-files/).
    written = 0
    resource_copies = 0
    for cat_dir in sorted(p for p in COMMANDS_DIR.iterdir() if p.is_dir()):
        cat = cat_dir.name
        md_files = [f for f in sorted(cat_dir.glob("*.md")) if f.name != "CLAUDE.md"]
        resources = [r for r in sorted(cat_dir.iterdir()) if r.suffix != ".md"]
        for md in md_files:
            name = f"{cat}-{md.stem}"
            description, body = parse_frontmatter(md.read_text(encoding="utf-8"))
            skill_dir = SKILLS_DIR / name
            skill_dir.mkdir(parents=True, exist_ok=True)
            (skill_dir / "SKILL.md").write_text(
                build_skill_md(name, description, body), encoding="utf-8"
            )
            (skill_dir / MARKER).write_text("generated by sync_commands_to_codex.py\n",
                                            encoding="utf-8")
            for res in resources:
                dest = skill_dir / res.name
                if res.is_dir():
                    shutil.copytree(res, dest, dirs_exist_ok=True)
                else:
                    shutil.copy2(res, dest)
                resource_copies += 1
                print(f"  resource: {cat}/{res.name} -> {name}/")
            written += 1
            print(f"skill: {md.relative_to(COMMANDS_DIR)} -> {name}/SKILL.md")

    print(f"\nDone. {written} skills written, {removed} stale removed, "
          f"{resource_copies} resource copies. Target: {SKILLS_DIR}")


def self_test():
    sample = (
        "---\n"
        "description: GIT commit changed and new files\n"
        "effort: low\n"
        "---\n\n"
        "Body line one.\nBody line two.\n"
    )
    desc, body = parse_frontmatter(sample)
    assert desc == "GIT commit changed and new files", desc
    assert body == "Body line one.\nBody line two.\n", repr(body)
    out = build_skill_md("git-commit", desc, body)
    assert out.startswith("---\nname: git-commit\n"), out
    assert "effort" not in out  # claude-only key dropped
    assert "Body line one." in out

    # No frontmatter -> whole text is body, name used as description.
    desc2, body2 = parse_frontmatter("Just a body.\n")
    assert desc2 is None and body2 == "Just a body.\n"
    out2 = build_skill_md("x-y", desc2, body2)
    assert "description: x-y" in out2
    print("self-test OK")


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        self_test()
    else:
        sync()
