"""Sync this repo's Claude `commands/` into Codex skills (~/.codex/skills/).

One-way: commands/ is the source of truth. Each commands/<cat>/<name>.md becomes
~/.codex/skills/<cat>-<name>/SKILL.md. Stale skills (from renamed/deleted commands)
are auto-removed via a marker file. Codex's own .system/ and symlinked skills are
never touched (no marker).

Run:  python sync_commands_to_codex.py        (or the .bat wrapper)
Test: python sync_commands_to_codex.py --self-test
"""

import shutil
import sys
import tempfile
from pathlib import Path
from unittest.mock import patch

from command_categories import (
    CATEGORIES_FILE,
    COMMANDS_DIR,
    SELECTION_FILE,
    list_categories,
    load_descriptions,
    load_selection,
    selected_categories,
)

SKILLS_DIR = Path.home() / ".codex" / "skills"
MARKER = ".synced-from-claude"

# Claude-only frontmatter keys that Codex skills don't use.
DROP_KEYS = {"effort", "allowed-tools", "argument-hint", "model", "name"}

# Body phrases that are fatal in Codex, which gets the body verbatim and has only a
# shell. Mentioning a Claude tool or subagent is fine when the body makes it
# conditional, so only the unconditional forms are listed. See "Write command bodies
# host-neutral" in commands/CLAUDE.md.
CLAUDE_ONLY_PHRASES = (
    "Do not use Bash",
    "use only Read",
    "Spawn exactly **one** Agent",
    "Use the Task tool",
)


def parse_frontmatter(text):
    """Return (description, body). description is None if absent.

    Only `description` is needed; we re-derive `name` from the path. The leading
    `---...---` block is stripped from body. Multi-line values aren't used by our
    commands, so a flat line parse is enough.
    """
    if not text.startswith("---"):
        return None, text
    lines = text.splitlines(keepends=True)
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end = i
            break
    if end is None:
        return None, text  # no closing fence; treat whole thing as body
    description = None
    for line in lines[1:end]:
        if ":" in line:
            key, _, val = line.partition(":")
            if key.strip() == "description":
                description = val.strip()
    body = "".join(lines[end + 1:]).lstrip("\n")
    return description, body


def build_skill_md(name, description, body):
    desc = description if description else name
    return f"---\nname: {name}\ndescription: {desc}\n---\n\n{body}"


def claude_only_warnings(body):
    """Return the Claude-only phrases present in a command body."""
    return [phrase for phrase in CLAUDE_ONLY_PHRASES if phrase in body]


def remove_stale(skills_dir):
    """Delete previously-synced skill folders (those carrying the marker)."""
    removed = 0
    if not skills_dir.exists():
        return removed
    for child in skills_dir.iterdir():
        if child.is_dir() and (child / MARKER).is_file():
            shutil.rmtree(child)
            removed += 1
    return removed


def sync():
    if not COMMANDS_DIR.is_dir():
        sys.exit(f"commands dir not found: {COMMANDS_DIR}")

    available_categories = list_categories(COMMANDS_DIR)
    load_descriptions(available_categories, CATEGORIES_FILE)
    saved_selection = load_selection(SELECTION_FILE)
    categories = selected_categories(available_categories, SELECTION_FILE)
    if saved_selection is None:
        print("Syncing all command categories (no selection saved).")
    else:
        selected = ", ".join(categories) if categories else "none"
        print(f"Syncing selected command categories: {selected}")

    SKILLS_DIR.mkdir(parents=True, exist_ok=True)

    removed = remove_stale(SKILLS_DIR)

    # Resource files per category = non-.md siblings (e.g. setup-files/).
    written = 0
    resource_copies = 0
    warnings = 0
    for cat in categories:
        cat_dir = COMMANDS_DIR / cat
        md_files = [f for f in sorted(cat_dir.glob("*.md")) if f.name != "CLAUDE.md"]
        resources = [r for r in sorted(cat_dir.iterdir()) if r.suffix != ".md"]
        for md in md_files:
            name = f"{cat}-{md.stem}"
            description, body = parse_frontmatter(md.read_text(encoding="utf-8"))
            skill_dir = SKILLS_DIR / name
            skill_dir.mkdir(parents=True, exist_ok=True)
            (skill_dir / "SKILL.md").write_text(
                build_skill_md(name, description, body), encoding="utf-8"
            )
            (skill_dir / MARKER).write_text("generated by sync_commands_to_codex.py\n",
                                            encoding="utf-8")
            for res in resources:
                dest = skill_dir / res.name
                if res.is_dir():
                    shutil.copytree(res, dest, dirs_exist_ok=True)
                else:
                    shutil.copy2(res, dest)
                resource_copies += 1
                print(f"  resource: {cat}/{res.name} -> {name}/")
            written += 1
            print(f"skill: {md.relative_to(COMMANDS_DIR)} -> {name}/SKILL.md")
            for phrase in claude_only_warnings(body):
                warnings += 1
                print(f"  WARNING: {name} contains Claude-only instruction: '{phrase}'")

    print(f"\nDone. {written} skills written, {removed} stale removed, "
          f"{resource_copies} resource copies, {warnings} warnings. "
          f"Target: {SKILLS_DIR}")
    if warnings:
        print("Claude-only instructions break the Codex copy - see "
              "'Write command bodies host-neutral' in commands/CLAUDE.md.")


def self_test():
    sample = (
        "---\n"
        "description: GIT commit changed and new files\n"
        "effort: low\n"
        "---\n\n"
        "Body line one.\nBody line two.\n"
    )
    desc, body = parse_frontmatter(sample)
    assert desc == "GIT commit changed and new files", desc
    assert body == "Body line one.\nBody line two.\n", repr(body)
    out = build_skill_md("git-commit", desc, body)
    assert out.startswith("---\nname: git-commit\n"), out
    assert "effort" not in out  # claude-only key dropped
    assert "Body line one." in out

    # No frontmatter -> whole text is body, name used as description.
    desc2, body2 = parse_frontmatter("Just a body.\n")
    assert desc2 is None and body2 == "Just a body.\n"
    out2 = build_skill_md("x-y", desc2, body2)
    assert "description: x-y" in out2
    # Claude-only body phrases are flagged; a host-neutral body is not.
    assert claude_only_warnings(
        "Tools: use only Read, Grep, Glob. Do not use Bash.") == [
        "Do not use Bash", "use only Read"]
    # A conditional mention of a Claude-only mechanism is correct, not a warning.
    assert claude_only_warnings(
        "If the host has subagents, spawn one (subagent_type: general-purpose); "
        "otherwise run inline. Claude: Grep; shell-only hosts: rg.") == []

    from command_categories import load_selection, save_selection, selected_categories

    with tempfile.TemporaryDirectory() as tmp:
        selection_file = Path(tmp) / "installed_categories.json"
        available = ["analyze", "git"]
        assert selected_categories(available, selection_file) == available
        save_selection(["retired", "git"], selection_file)
        assert load_selection(selection_file) == ["git", "retired"]
        assert selected_categories(available, selection_file) == ["git"]

        commands_dir = Path(tmp) / "commands"
        skills_dir = Path(tmp) / "skills"
        for category in available:
            category_dir = commands_dir / category
            category_dir.mkdir(parents=True)
            (category_dir / "one.md").write_text(
                f"---\ndescription: {category} command\n---\n\nBody.\n",
                encoding="utf-8",
            )
        descriptions_file = commands_dir / "categories.json"
        descriptions_file.write_text(
            '{"analyze": "Analyze code.", "git": "Manage Git."}\n',
            encoding="utf-8",
        )
        save_selection(["git"], selection_file)
        stale_skill = skills_dir / "old-command"
        stale_skill.mkdir(parents=True)
        (stale_skill / MARKER).write_text("generated\n", encoding="utf-8")
        with patch.multiple(
            __name__,
            COMMANDS_DIR=commands_dir,
            CATEGORIES_FILE=descriptions_file,
            SELECTION_FILE=selection_file,
            SKILLS_DIR=skills_dir,
        ):
            sync()
        assert (skills_dir / "git-one" / "SKILL.md").is_file()
        assert not (skills_dir / "analyze-one").exists()
        assert not stale_skill.exists()

    print("self-test OK")


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        self_test()
    else:
        sync()
